// String properties and Basic access

let str = "Hello, World!";
console.log(str.length); // Outputs: 13
console.log(str[0]); // Outputs: H
console.log(str[7]); // Outputs: W
console.log(str.at(-2)); // Outputs: d (accessing the second last character using at() method)
console.log(str.charAt(4)); // Outputs: o (using charAt() method)
console.log(str.charCodeAt(0)); // Outputs: 72 (ASCII code of 'H')
