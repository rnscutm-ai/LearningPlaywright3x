// Assignment Operator
// The assignment operator (=) is used to assign a value to a variable.

let x = 5; // Assigning the value 5 to variable x
console.log(x); // Output: 5

let y = 10; // Assigning the value 10 to variable y
console.log(y); // Output: 10

let z = x + y; // Assigning the sum of x and y to variable z
console.log(z); // Output: 15

let a = "Rabindra;" // Assigning a string value to variable a
console.log(a); // Output: Rabindra;


// some more examples of assignment operators
// Addition Assignment (+=), Subtraction Assignment (-=), Multiplication Assignment (*=), Division Assignment (/=), Modulus Assignment (%=), Exponentiation Assignment (**=)
let p = 5;
p += 3; // Equivalent to p = p + 3
console.log(p); // Output: 8

let q = 10;
q -= 4; // Equivalent to q = q - 4
console.log(q); // Output: 6    

let r = 2;
r *= 3; // Equivalent to r = r * 3
console.log(r); // Output: 6    

let s = 20;
s /= 4; // Equivalent to s = s / 4
console.log(s); // Output: 5    

let t = 10;
t %= 3; // Equivalent to t = t % 3
console.log(t); // Output: 1

let u = 2;
u **= 3; // Equivalent to u = u ** 3
console.log(u); // Output: 8

let v = 5;
v &= 3; // Equivalent to v = v & 3
console.log(v); // Output: 1

let w = 5;
w |= 3; // Equivalent to w = w | 3
console.log(w); // Output: 7

let x1 = 5;
x1 ^= 3; // Equivalent to x1 = x1 ^ 3
console.log(x1); // Output: 6

