// Arithmetic Operators
// Addition (+)
let a = 10;
let b = 5;
let sum = a + b; // sum is 15   
console.log(sum); // Output: 15

// Subtraction (-)
let difference = a - b; // difference is 5
console.log(difference); // Output: 5   

// Multiplication (*)
let product = a * b; // product is 50
console.log(product); // Output: 50 

// Division (/)
let quotient = a / b;
console.log(quotient); // Output: 2

// Modulus (%)
let remainder = a % b; // remainder is 0
console.log(remainder); // Output: 0

// Increment (++)
let c = 10;
c++;    
console.log(c); // Output: 11

// Decrement (--)
let d = 10;
d--;    
console.log(d); // Output: 9    

// Exponentiation (**)
let e = 2;
let f = 3;
let power = e ** f;
console.log(power); // Output: 8

// Unary Plus (+)
let g = "5";
let unaryPlus = +g; 
console.log(unaryPlus); // Output: 5

// Unary Negation (-)
let h = 5;
let unaryNegation = -h; 
console.log(unaryNegation); // Output: -5   

