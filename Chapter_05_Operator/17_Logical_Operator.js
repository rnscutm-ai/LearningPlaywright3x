// && --> and gate
// || --> or gate
// ! --> not gate   

let a=true;
let b=false;

console.log(a && b); // Output: false , both a and b should be true to return true
console.log(a || b); // Output: true , either a or b should be true to return true
console.log(!a); // Output: false , not gate reverses the boolean value 


